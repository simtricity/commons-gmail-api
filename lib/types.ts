/**
 * Wire and domain types for the Gmail REST API subset this package covers.
 * @module
 */

/** The `installed`/`web` block of a Google Cloud Console OAuth client download. */
export interface ClientSecret {
  /** OAuth 2.0 client id from the Google Cloud console. */
  clientId: string;
  /** OAuth 2.0 client secret. Never log it. */
  clientSecret: string;
}

/** One mailbox's OAuth grant as persisted by a {@link TokenStore}. */
export interface OAuthCredential {
  /** Long-lived at Google until revoked. The secret that matters. */
  refreshToken: string;
  /** ~1h. Refreshed transparently by the client. */
  accessToken: string;
  /** ISO 8601 UTC. */
  accessTokenExpiresAt: string;
  /** Mailbox address, from `users.getProfile`. Used as the store key. */
  email: string;
  /** Space-separated scopes Google actually granted. */
  scope: string;
  /** ISO 8601 UTC of the login that minted the refresh token. */
  savedAt: string;
  /** ISO 8601 UTC of the last successful access-token refresh. Absent until the first one. */
  lastRefreshAt?: string;
  /** The last refresh failure, cleared by the next success. Absent when the last refresh worked. */
  lastRefreshError?: RefreshFailure;
}

/** A failed access-token refresh, as recorded on the credential and reported to `onAuthEvent`. */
export interface RefreshFailure {
  /** ISO 8601 UTC. */
  at: string;
  /** HTTP status from Google; absent when it could not be reached. */
  status?: number;
  /** Google's OAuth `error` code, e.g. `invalid_grant`. */
  code?: string;
  /** True when Google refused the sign-in (a new login is needed); false when it may pass. */
  rejected: boolean;
}

/**
 * A sign-in event, for a caller's own log. `GmailClient` emits the `refresh-*` events; `login`
 * and `logout` are for callers that perform those. Never carries a token or secret.
 */
export interface AuthEvent {
  /** ISO 8601 UTC. */
  at: string;
  /**
   * `refresh-retry`: a refresh attempt failed and will be retried. `refresh-recovered`: a refresh
   * succeeded after retries. `refresh-failed`: retries ran out on a failure that may pass.
   * `refresh-rejected`: Google refused the sign-in.
   */
  event:
    | "refresh-retry"
    | "refresh-recovered"
    | "refresh-failed"
    | "refresh-rejected"
    | "login"
    | "logout";
  /** The mailbox. */
  account: string;
  /** Attempt number, for refresh events. */
  attempt?: number;
  /** HTTP status from Google, when there was one. */
  status?: number;
  /** Google's OAuth `error` code, when it sent one. */
  code?: string;
  /** Scopes granted, for `login`. */
  scopes?: string[];
}

/**
 * Where credentials live. The library ships {@link FileTokenStore}; callers with their
 * own policy (TTL sweeps, keychains, per-tenant keying) implement this instead.
 */
export interface TokenStore {
  /** `account` omitted → the store's default account, or null if none. */
  load(account?: string): Promise<OAuthCredential | null>;
  /** Insert or replace the credential for `cred.email`. */
  save(cred: OAuthCredential): Promise<void>;
  /** Forget `account` (case-insensitive). */
  delete(account: string): Promise<void>;
  /** Mailbox addresses with a stored credential. */
  list(): Promise<string[]>;
}

// ── Gmail API wire shapes (the fields we read; the API returns more) ──────────

/** One MIME header on a message part, as Gmail returns it. */
export interface MessagePartHeader {
  /** Header name as sent, e.g. `Content-Disposition`. */
  name: string;
  /** Header value as sent. */
  value: string;
}

/** Body of a MIME part. Large bodies carry an `attachmentId` instead of inline `data`. */
export interface MessagePartBody {
  /** Id for `users.messages.attachments.get`. Ephemeral; do not persist. */
  attachmentId?: string;
  /** Decoded size in bytes. */
  size?: number;
  /** base64url. Present for small inline bodies, absent when `attachmentId` is set. */
  data?: string;
}

/** A node in a message's MIME tree, as Gmail returns it. */
export interface MessagePart {
  /** Gmail's part id, e.g. `0.1`. */
  partId?: string;
  /** MIME type of this part. */
  mimeType?: string;
  /** Filename for attachment parts; empty for body parts. */
  filename?: string;
  /** Headers on this part. */
  headers?: MessagePartHeader[];
  /** Body or attachment pointer for this part. */
  body?: MessagePartBody;
  /** Child parts for multipart types. */
  parts?: MessagePart[];
}

/** A Gmail message as returned by `users.messages.get`. */
export interface Message {
  /** Gmail message id (hex). */
  id: string;
  /** Id of the thread this message belongs to. */
  threadId: string;
  /** Label ids applied to the message. */
  labelIds?: string[];
  /** Short plain-text preview generated by Gmail. */
  snippet?: string;
  /** Mailbox history id at last change. */
  historyId?: string;
  /** ms since epoch as a string. */
  internalDate?: string;
  /** Gmail's estimate of the message size in bytes. */
  sizeEstimate?: number;
  /** Root of the MIME tree; absent for `raw`/`minimal` formats. */
  payload?: MessagePart;
  /** Only with `format=raw`. */
  raw?: string;
}

/** A Gmail thread as returned by `users.threads.get`. */
export interface Thread {
  /** Gmail thread id (hex). */
  id: string;
  /** Mailbox history id at last change. */
  historyId?: string;
  /** Messages in the thread, oldest first. */
  messages?: Message[];
}

/** Response of `users.messages.list`. */
export interface MessageListResponse {
  /** Matching message ids with their thread ids; absent when there are no results. */
  messages?: { id: string; threadId: string }[];
  /** Token for the next page, if any. */
  nextPageToken?: string;
  /** Gmail's rough count of total matches. */
  resultSizeEstimate?: number;
}

/** Response of `users.getProfile`. */
export interface Profile {
  /** The mailbox address. */
  emailAddress: string;
  /** Total messages in the mailbox. */
  messagesTotal: number;
  /** Total threads in the mailbox. */
  threadsTotal: number;
  /** Current mailbox history id. */
  historyId: string;
}

/** A send-as address, from `users.settings.sendAs.list`: the primary address and any aliases. */
export interface SendAs {
  /** The address mail is sent from. */
  sendAsEmail: string;
  /** The display name used with it. */
  displayName?: string;
  /** Reply-To set for this address, if any. */
  replyToAddress?: string;
  /** The signature, as HTML, from the account holder's Gmail settings. */
  signature?: string;
  /** True for the account's own address. */
  isPrimary?: boolean;
  /** True for the address new mail is sent from by default. */
  isDefault?: boolean;
}

/** A Gmail label as returned by `users.labels.get`/`list`. */
export interface Label {
  /** Label id, e.g. `INBOX` or `Label_12`. */
  id: string;
  /** Display name. */
  name: string;
  /** System labels are Gmail's built-ins; user labels are custom. */
  type?: "system" | "user";
  /** Messages carrying this label. */
  messagesTotal?: number;
  /** Unread messages carrying this label. */
  messagesUnread?: number;
  /** Threads carrying this label. */
  threadsTotal?: number;
  /** Unread threads carrying this label. */
  threadsUnread?: number;
}

/** Payload shape for `users.messages.get` and `users.threads.get`. */
export type MessageFormat = "full" | "metadata" | "minimal" | "raw";

// ── Domain shapes this package adds ──────────────────────────────────────────

/**
 * An attachment located in a message's MIME tree.
 *
 * `attachmentId` is NOT stable across `messages.get` calls — fetch, use, discard. Never
 * persist one and look it up later.
 */
export interface AttachmentRef {
  /** Id of the message that carries the attachment. */
  messageId: string;
  /** Filename as sent. */
  filename: string;
  /** Ephemeral id for `users.messages.attachments.get`; fetch-then-use. */
  attachmentId: string;
  /** MIME type; `application/octet-stream` when Gmail omits it. */
  mimeType: string;
  /** Bytes, per Gmail's `body.size`. */
  size: number;
  /** `Content-Disposition: inline` with a `Content-ID` — an embedded image, usually. */
  inline: boolean;
}

/** One file written by a fetch. */
export interface ManifestEntry {
  /** Id of the message the file came from. */
  messageId: string;
  /** As sent, including Gmail's ` (1)` suffixes. */
  filename: string;
  /** Basename actually written; differs from `filename` only on a collision. */
  savedAs: string;
  /** Absolute path of the written file. Absent on `dryRun`. */
  path?: string;
  /** MIME type as reported by Gmail. */
  mimeType: string;
  /** Bytes written, or Gmail's `body.size` on `dryRun`. */
  bytes: number;
  /** Hex. Absent on `dryRun`. */
  sha256?: string;
}

/** Record of one fetch run, written as `manifest.json` in `outDir`. */
export interface Manifest {
  /** Thread id, or the single message id for a message-scoped fetch. */
  source: { threadId?: string; messageId?: string };
  /** Mailbox address the fetch ran as. */
  account: string;
  /** ISO 8601 UTC. */
  fetchedAt: string;
  /** Absolute path files were written to. */
  outDir: string;
  /** Files written (or that would be written on `dryRun`). */
  files: ManifestEntry[];
  /**
   * Attachments present in the source but not written: excluded by `include`/`filenames`/
   * `inline`/`maxBytes` rules, or already on disk when `skipExisting` is set (reason starts
   * `already in <dir>`).
   */
  skipped: { messageId: string; filename: string; reason: string }[];
}

/** Options for creating or updating a label. */
export interface LabelOptions {
  /** Show in the label list always, only when unread, or never. */
  labelListVisibility?: "labelShow" | "labelShowIfUnread" | "labelHide";
  /** Whether messages carrying the label appear in the message list. */
  messageListVisibility?: "show" | "hide";
}

/** A label change applied to messages or threads. Ids, not names. */
export interface LabelChange {
  /** Label ids to add. */
  addLabelIds?: string[];
  /** Label ids to remove. */
  removeLabelIds?: string[];
  /**
   * Permit `TRASH`, `SPAM` and `INBOX`. Off by default because removing `INBOX` archives and
   * adding `TRASH` trashes: a labelling run must not do either by accident.
   */
  allowSystem?: boolean;
}

/** Input for a new draft: text, optionally HTML, files, and a reply's thread and quote. */
export interface DraftInput {
  /** Recipients. Optional when replying: defaults to the original's Reply-To or From. */
  to?: string[];
  /** Cc recipients. */
  cc?: string[];
  /** Bcc recipients. */
  bcc?: string[];
  /** Subject. When replying, defaults to `Re: <original subject>`. */
  subject?: string;
  /** Plain-text body, UTF-8. Always sent; with an HTML body it is the plain alternative. */
  text: string;
  /**
   * The body as HTML, sent as given (it is the caller's own; nothing is sanitised). Absent: when
   * an HTML part is needed (a quote, a signature), it is the escaped text.
   */
  html?: string;
  /** Reply in the thread of this message: sets threadId, In-Reply-To and References. */
  replyToMessageId?: string;
  /**
   * Quote the original under the reply, as Gmail does. Default true when replying; ignored
   * otherwise. The quote is the original's text, escaped: never its HTML.
   */
  quote?: boolean;
  /**
   * Reply to everyone on the original, as Gmail does: needs `replyToMessageId`. Your own
   * addresses (the profile and every send-as) are left out, Bcc is never computed, a given `to`
   * replaces the computed one and a given `cc` is added to it.
   */
  replyAll?: boolean;
  /**
   * Add the send-as signature of the draft's From address (the default send-as, else the
   * primary), after the new body and above any quote, as Gmail places it. Its HTML is scrubbed
   * of scripts, styles, event handlers and `javascript:` URLs; images are kept.
   */
  signature?: boolean;
  /** Files to attach, as bytes. The library never reads paths; callers load the files. */
  attachments?: DraftAttachment[];
}

/** A draft built but not yet written: the message, and what went into it. */
export interface DraftPlan {
  /** The `message` resource to post: the raw RFC 5322 bytes, and the thread when replying. */
  message: { raw: string; threadId?: string };
  /** The recipients exactly as written into the message. */
  recipients: { to: string[]; cc: string[]; bcc: string[] };
  /** True when the original was quoted under the reply. */
  quoted: boolean;
  /** `added`; `none` when asked for but no signature is set; `off` when not asked for. */
  signature: "added" | "none" | "off";
}

/** Input for a forward draft. */
export interface ForwardInput {
  /** The message to forward. */
  messageId: string;
  /** Recipients: required. Nothing is computed from the original. */
  to: string[];
  /** Cc recipients. */
  cc?: string[];
  /** Bcc recipients. */
  bcc?: string[];
  /** Your note above the forwarded message. May be empty. */
  text?: string;
  /** Your note as HTML, sent as given. */
  html?: string;
  /**
   * The original's files to carry: `all` (default), `none`, or exact filenames. A name that
   * matches no regular file throws before any download. Inline images are never carried; they
   * are reported in `skippedInline`.
   */
  attachments?: "all" | "none" | string[];
  /** Add the send-as signature, as for {@link DraftInput.signature}. */
  signature?: boolean;
}

/** What a forward carried from the original. */
export interface CarriedSummary {
  /** Files carried. */
  count: number;
  /** Their total bytes. */
  totalBytes: number;
  /** sha256 (hex) of each, in order. */
  sha256: string[];
}

/** A forward built but not yet written. */
export interface ForwardPlan {
  /** The `message` resource to post. */
  message: { raw: string; threadId?: string };
  /** The recipients exactly as written into the message. */
  recipients: { to: string[]; cc: string[]; bcc: string[] };
  /** The files carried from the original. */
  carried: CarriedSummary;
  /** Inline parts of the original that were not carried (signature logos, pasted images). */
  skippedInline: number;
  /** As for {@link DraftPlan.signature}. */
  signature: "added" | "none" | "off";
}

/** Input for editing a draft. Anything not given is kept. */
export interface UpdateDraftInput {
  /** The draft to edit (its draft id, not its message id). */
  draftId: string;
  /** New text: replaces your text above any quote. With neither text nor html, the body is kept. */
  text?: string;
  /** New HTML body, sent as given. */
  html?: string;
  /** New subject. */
  subject?: string;
  /** New To, replacing the old one whole. Absent or empty: the draft's To is kept. */
  to?: string[];
  /** New Cc, replacing the old one whole. Absent or empty: the draft's Cc is kept. */
  cc?: string[];
  /** New Bcc, replacing the old one whole. Absent or empty: the draft's Bcc is kept. */
  bcc?: string[];
  /** Files to add. */
  addAttachments?: DraftAttachment[];
  /** Files to remove, by exact filename; an unknown name throws before any write. */
  removeAttachments?: string[];
  /**
   * When the body is rebuilt and the draft is a reply: regenerate the quote from the original
   * (default true). Old quote text is never parsed back out of the draft.
   */
  quote?: boolean;
  /** When the body is rebuilt: add the signature. Default: whether the draft had one. */
  signature?: boolean;
  /** Refuse with `DraftChangedError` unless the draft's message id is still this. */
  expectMessageId?: string;
}

/** An edit built but not yet written. */
export interface UpdatePlan {
  /** The draft being edited. */
  draftId: string;
  /** Its message id when read; checked again just before the write. */
  previousMessageId: string;
  /** The `message` resource to put. */
  message: { raw: string; threadId?: string };
  /** The recipients exactly as written into the message. */
  recipients: { to: string[]; cc: string[]; bcc: string[] };
  /** `kept`: the old text and HTML parts as they were; `rebuilt`: through the composer. */
  body: "kept" | "rebuilt";
  /** Files kept from the draft, with their sha256 (equal before and after). */
  kept: { count: number; sha256: string[] };
  /** Files added. */
  added: number;
  /** Files removed. */
  removed: number;
  /** True when the draft's body holds a quote of the original. */
  quoted: boolean;
  /** `added` or `none` when a rebuild asked for one; `off` otherwise; `added` when a kept body has one. */
  signature: "added" | "none" | "off";
}

/** A file attached to a draft. */
export interface DraftAttachment {
  /** Filename shown to the recipient. */
  filename: string;
  /** File bytes. */
  content: Uint8Array;
  /** MIME type. Default: guessed from the filename's extension. */
  mimeType?: string;
}

/** A Gmail draft as returned by `users.drafts.*`. */
export interface Draft {
  /** Draft id. Distinct from the message id. */
  id: string;
  /** The draft's message (id, threadId, labelIds). */
  message: { id: string; threadId?: string; labelIds?: string[] };
}

/** One draft in a listing: its ids and the headers that tell drafts apart. */
export interface DraftSummary {
  /** Draft id (what update and delete take). */
  id: string;
  /** The draft's current message id; it changes on every update. */
  messageId: string;
  /** The thread the draft is in. */
  threadId?: string;
  /** `Subject`, as written. */
  subject: string;
  /** `To`, as written. */
  to: string;
  /** `Date`, as written. */
  date: string;
}
